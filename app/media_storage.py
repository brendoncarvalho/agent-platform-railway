"""
Media Storage
=============

The agno `MediaStorage` backend shared by the agents. Images uploaded by users and images
generated by tools are offloaded here by agno at the end of each run; the AgentOS media
route (`/sessions/{session_id}/media/{storage_key}`) streams them back to the UI.

Backends (env `MEDIA_STORAGE`):
- `local` (default): files under `MEDIA_STORAGE_DIR` (`storage/media`). Mount a volume in prod.
- `s3`: an S3-compatible bucket (`MEDIA_S3_*`, credentials via the standard AWS env vars).
  Requires `boto3`.
"""

from functools import cache

from agno.media.storage.base import MediaStorage
from agno.media.storage.local import LocalMediaStorage

from app.settings import media_storage_settings


@cache
def get_media_storage() -> MediaStorage:
    """Shared storage instance built from the environment (memoized)."""
    settings = media_storage_settings()
    if settings.backend == "s3":
        if not settings.s3_bucket:
            raise ValueError("MEDIA_STORAGE=s3 requires MEDIA_S3_BUCKET.")
        try:
            from agno.media.storage.s3 import S3MediaStorage
        except ImportError as exc:  # pragma: no cover - depends on an optional dependency
            raise ImportError("MEDIA_STORAGE=s3 requires boto3: `pip install boto3`.") from exc
        return S3MediaStorage(
            bucket=settings.s3_bucket,
            prefix=settings.s3_prefix,
            region=settings.s3_region,
            endpoint_url=settings.s3_endpoint_url,
        )
    return LocalMediaStorage(base_path=str(settings.local_dir))
